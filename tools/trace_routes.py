"""Trace the beat-detail route map's legs along the streets of its image.

The map (src/maps/beat-map.webp) is a picture, with no road data, so the
streets are read off its pixels: the blue-grey road colour, with labels
and arrows closed over, and a shortest path along it between each pair
of stops, kept to the middle of the road. Every pair within a day is
traced, not only neighbours, so the route still follows the streets when
a visit between two stops leaves it (rejected, awaiting).

Writes src/beat-routes.js. Run after moving a stop:

    python3 tools/trace_routes.py

Needs macOS (swiftc, CoreGraphics). STOPS must match BEAT_HOME,
BEAT_OFFICE and each day's `pins` in src/beat-detail.js.
"""
import os, subprocess, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HOME, OFFICE = (236, 618), (688, 546)
DAYS = [
    [(186, 314), (218, 468), (286, 510), (362, 562)],
    [(392, 256), (434, 210), (564, 194)],
    [(530, 370), (616, 480)],
]


def main():
    pairs = []
    for pins in DAYS:
        stops = [HOME, *pins, OFFICE]
        pairs += [(stops[i], stops[j]) for i in range(len(stops)) for j in range(i + 1, len(stops))]
    pairs = list(dict.fromkeys(pairs))

    with tempfile.TemporaryDirectory() as tmp:
        exe = os.path.join(tmp, 'trace_routes')
        subprocess.run(['swiftc', '-O', '-o', exe, os.path.join(ROOT, 'tools', 'trace_routes.swift')],
                       check=True, capture_output=True)
        out = subprocess.run([exe, os.path.join(ROOT, 'src', 'maps', 'beat-map.webp'),
                              *(f'{a[0]},{a[1]};{b[0]},{b[1]}' for a, b in pairs)],
                             check=True, capture_output=True, text=True).stdout

    legs = [l.strip() for l in out.split('--')[:-1]]
    lines = []
    for (a, b), leg in zip(pairs, legs):
        if leg == 'FAIL':
            raise SystemExit(f'no street path from {a} to {b}')
        pts = ', '.join(f'[{p}]' for p in leg.split(';'))
        lines.append(f"  '{a[0]},{a[1]}>{b[0]},{b[1]}': [{pts}],")

    with open(os.path.join(ROOT, 'src', 'beat-routes.js'), 'w') as f:
        f.write('/* ============================================================\n'
                '   Beat map routes, along the streets of src/maps/beat-map.webp.\n'
                '   Generated by tools/trace_routes.py — do not edit by hand.\n'
                "   Keyed 'x,y>x,y' from one stop to the next, in map world units;\n"
                '   each value is the leg as a polyline, ends included.\n'
                '   ============================================================ */\n'
                'window.BEAT_ROUTES = {\n' + '\n'.join(lines) + '\n};\n')
    print(f'{len(lines)} legs -> src/beat-routes.js')


if __name__ == '__main__':
    main()
